function cat = abl_catalog()
% ABL_CATALOG  Factors of the AoA ablation study: codebook sizes, noise models, user/chart
% structures, features, and the scenario list. The texts are used in the README files.

    % Phase step between adjacent elements per EMS for a K x K codebook [deg/element].
    % narrow: 0..40 (as all earlier runs; 3x3 = the reference coarse run) steers the beam only
    %         within a ~16-28 deg sector on the side away from the BS.
    % wide  : K steps spread evenly over -180..180, i.e. beams spread evenly in sin(theta) over
    %         all directions (lambda/2 spacing: sin(theta_beam) = sin(theta_specular) + step/180).
    wide = @(K) sort(mod((0:K-1)*360/K + 180, 360) - 180);
    cat.codebooks = [ ...
        struct('id','narrow', 'tok','', 'levels',{{0, [0 40], [0 20 40], [0 40/3 80/3 40], [0 10 20 30 40]}}, ...
               'text','phase steps 0..40 deg/element (beam steered only within a ~16-28 deg sector away from the BS), as all earlier runs'), ...
        struct('id','wide', 'tok','_cb-wide', 'levels',{arrayfun(wide, 1:5, 'UniformOutput', false)}, ...
               'text','phase steps spread evenly over -180..180 deg/element (beams spread evenly over all directions)')];
    cat.levels = cat.codebooks(1).levels;     % default (narrow)

    nz = @(name, g, txt) struct('name',name, 'tx_dBm',23, 'noise_dBm',-92, ...
                                'pilot_gain_dB',g, 'text',txt);
    cat.noise = [ ...
        nz('noiseless', NaN, ['Exact covariance (no estimation noise), as all earlier runs. ' ...
           'A floor of 2*sigma_n^2/sigma_s^2 (sigma_s^2 = 23 dBm, sigma_n^2 = -92 dBm) is added only ' ...
           'to keep it invertible; this replaces the old fixed 1e-6, which was 55 dB higher.']), ...
        nz('est_G0dB', 0, ['Estimated channels: each of the N_real = 500 snapshots is H*g + E, ' ...
           'E ~ CN(0, sigma_n^2/sigma_s^2), i.e. one pilot symbol per snapshot (no pilot gain).']), ...
        nz('est_G30dB', 30, ['Estimated channels as est_G0dB, with a 30 dB pilot processing gain ' ...
           '(noise variance on each estimate divided by 1000).']), ...
        nz('est_G60dB', 60, ['Estimated channels as est_G0dB, with a 60 dB pilot processing gain ' ...
           '(noise variance on each estimate divided by 10^6).'])];

    st = @(id, tok, txt) struct('id',id, 'tok',tok, 'text',txt);
    cat.structures = [ ...
        st('S1', 'S1-joint', ['One joint 2-D t-SNE chart whose coordinates are the azimuths from ' ...
           'EMS1 and EMS2. Users: those in front of both surfaces; anchors: 15% of them. Same ' ...
           'structure as the reference runs (results_aoa/coarse_3x3, full_11x11).']), ...
        st('S2', 'S2-perEMS', ['Two separate 1-D t-SNE charts, one per surface, each labelled ' ...
           'only with that surface''s azimuth. Chart e uses every user in front of surface e ' ...
           '(also those behind the other surface); anchors: 15% of them. No coupling between ' ...
           'the two angles (no triangulation).']), ...
        st('S3', 'S3-joint-allUE', ['Joint 2-D chart as S1, but t-SNE sees ALL users, ' ...
           'including those behind one surface (they have no valid joint label, so they are ' ...
           'unlabelled points only). Anchors: the same as S1. Also scored on all users against ' ...
           'their geometric azimuth (beyond +-90 deg for users behind a surface, error wrapped ' ...
           'to +-180 deg) as the worst case.']), ...
        st('S4', 'S4-perEMS-frontboth', ['Two 1-D per-surface charts as S2, but on exactly the ' ...
           'S1 users and anchors: isolates "joint vs separate charts" with identical users.'])];

    ft = @(id, tok, minK, txt) struct('id',id, 'tok',tok, 'minK',minK, 'text',txt);
    cat.features = [ ...
        ft('F0', 'F0-cov-per-sweep', 1, ['Full covariance of each acquisition: one chart per ' ...
           'EMS configuration, then fusion across configurations (global and local ' ...
           'quality-weighted), as in the reference.']), ...
        ft('F1', 'F1-stacked-cov', 2, ['All acquisitions combined into one feature: the ' ...
           'log-covariances of all configurations are stacked and give one chart (no fusion). ' ...
           'Control for F2/F3: isolates "one chart from all sweeps" vs "per-sweep charts + ' ...
           'fusion". (For K = 1 it equals F0.)']), ...
        ft('F2', 'F2-sweep-change', 2, ['Sweep changes: per user, the log-covariance of each ' ...
           'configuration minus that user''s mean over the configurations, stacked; one chart. ' ...
           'Removes, in the log domain, everything that does not change with the surface ' ...
           'phases (direct path, static scattering). Joint charts centre over all K^2 ' ...
           'configurations; per-surface charts centre along their own surface''s sweep with the ' ...
           'other surface fixed. Needs K >= 2.']), ...
        ft('F3', 'F3-off-subtract', 1, ['OFF subtraction: per configuration, the log-covariance ' ...
           'with the surface(s) on minus the log-covariance of an extra acquisition with the ' ...
           'surface(s) ideally off (absorbing), stacked; one chart. Joint charts switch both ' ...
           'surfaces off (1 extra acquisition); per-surface charts switch off only their own ' ...
           'surface (one extra acquisition per phase of the other surface). This is the ON/OFF ' ...
           'protocol of RIS channel estimation, used here at covariance level.'])];

    % Scenario list of the matrix stage
    S = struct('structure',{}, 'feature',{}, 'direct',{}, 'Ks',{}, 'codebook',{});
    for cb = {'narrow','wide'}
        for s = {'S1','S2','S3'}
            for f = {'F0','F1','F2','F3'}
                for d = [true false]
                    if strcmp(f{1},'F3') && ~d, continue; end   % OFF state would be noise only
                    S(end+1) = struct('structure',s{1}, 'feature',f{1}, 'direct',d, 'Ks',1:5, 'codebook',cb{1}); %#ok<AGROW>
                end
            end
        end
        S(end+1) = struct('structure','S4', 'feature','F0', 'direct',true, 'Ks',3, 'codebook',cb{1}); %#ok<AGROW>
    end
    for i = 1:numel(S)
        fi = strcmp({cat.features.id}, S(i).feature);
        S(i).Ks = S(i).Ks(S(i).Ks >= cat.features(fi).minK);
        S(i).name = abl_name(cat, S(i));
    end
    cat.scenarios = S;
end

function n = abl_name(cat, s)
    d = {'dir-off','dir-on'};
    n = sprintf('%s_%s_%s%s', cat.structures(strcmp({cat.structures.id}, s.structure)).tok, ...
                cat.features(strcmp({cat.features.id}, s.feature)).tok, d{s.direct+1}, ...
                cat.codebooks(strcmp({cat.codebooks.id}, s.codebook)).tok);
end
